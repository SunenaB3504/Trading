import { writeFileSync } from 'node:fs';

/**
 * Pulls daily USD/INR from Yahoo (symbol INR=X) and writes the small data module the F&O desk uses for currency
 * futures (MIP v4.1 Stage 9): `packages/app/src/fno/usdinr.generated.ts`. Yahoo is not the exchange, so the series is a
 * stand-in for the NSE currency file (rule E7: cross-check source only). Rates are stored in ten-thousandths of a
 * rupee. Run again to extend it.
 *
 * Usage:  pnpm pull:usdinr [--from 2018-01-01]
 */
const OUT = 'packages/app/src/fno/usdinr.generated.ts';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36';

interface Chart {
  chart: { result: { timestamp: number[]; indicators: { quote: { open: (number | null)[]; close: (number | null)[] }[] } }[] };
}

/** The calendar date of a Yahoo timestamp for a London-hours market: midnight local shows as 23:00 UTC the day before. */
const dateOf = (t: number): string => new Date((t + 2 * 3600) * 1000).toISOString().slice(0, 10);

async function main(): Promise<void> {
  const i = process.argv.indexOf('--from');
  const from = i >= 0 ? (process.argv[i + 1] ?? '2018-01-01') : '2018-01-01';
  const p1 = Math.floor(Date.parse(`${from}T00:00:00Z`) / 1000);
  const p2 = Math.floor(Date.now() / 1000) + 86_400;
  const res = await fetch(`https://query1.finance.yahoo.com/v8/finance/chart/INR%3DX?period1=${String(p1)}&period2=${String(p2)}&interval=1d`, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Yahoo answered ${String(res.status)}`);
  const r = ((await res.json()) as Chart).chart.result[0];
  const q = r?.indicators.quote[0];
  if (r === undefined || q === undefined) throw new Error('no data in the answer');
  const rows = new Map<string, [number, number]>();
  r.timestamp.forEach((t, k) => {
    const o = q.open[k];
    const c = q.close[k];
    if (o == null || c == null || o <= 0 || c <= 0) return;
    rows.set(dateOf(t), [Math.round(o * 10_000), Math.round(c * 10_000)]);
  });
  const dates = [...rows.keys()].sort();
  const lines = dates.map((d) => `  ['${d}', ${String(rows.get(d)?.[0])}, ${String(rows.get(d)?.[1])}],`);
  const body = [
    '// Generated by `pnpm pull:usdinr` from Yahoo INR=X. Do not edit by hand. [date, open, close] in ten-thousandths of a rupee.',
    `export const USDINR_FROM = '${dates[0]}';`,
    `export const USDINR_TO = '${dates[dates.length - 1]}';`,
    'export const USDINR_ROWS: ReadonlyArray<readonly [string, number, number]> = [',
    ...lines,
    '];',
    '',
  ].join('\n');
  writeFileSync(OUT, body);
  process.stdout.write(`wrote ${String(dates.length)} days, ${dates[0]} to ${dates[dates.length - 1]}\n`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
