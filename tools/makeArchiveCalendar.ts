/**
 * Writes `packages/core/src/calendar/archiveCalendar.generated.ts` from the files the exchange published
 * (WP-2.9): a weekday on which neither the bhavcopy nor the PR archive exists is a holiday, and a weekend
 * bhavcopy is a special session. It refuses to write while any weekday is unsettled, because a gap in
 * the pull would otherwise turn into a false holiday.
 *
 * Usage:  pnpm tsx tools/makeArchiveCalendar.ts --from 2018-01-01 --to 2019-12-31 [--dir data/raw/nse-bars]
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { dayEvidence, deriveCalendar } from '../packages/data-service/src/index';
import { FileRawStore } from '../packages/data-service/src/index';

/**
 * Diwali evening sessions. A Muhurat session on an ordinary weekday looks like any other trading day
 * in the files, so these dates come from this list; the evening hours are recalled, not read.
 */
const MUHURAT: Record<string, string> = {
  '2018-11-07': 'Diwali Laxmi Pujan, Wednesday evening session',
  '2019-10-27': 'Diwali Laxmi Pujan, Sunday evening session',
};
const MUHURAT_WINDOW = { open: '18:15', close: '19:15' };
const DR_WINDOWS = [
  { open: '09:15', close: '10:00' },
  { open: '11:30', close: '12:30' },
];

function option(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function render(from: string, to: string, cal: ReturnType<typeof deriveCalendar>): string {
  const holidays = cal.holidays.map((date) => ({
    date,
    name: 'closed (no exchange files)',
    confidence: 'archive',
    source: 'NSE bhavcopy and PR archive both absent',
  }));
  const special = [
    ...cal.weekendSessions,
    ...Object.keys(MUHURAT).filter((d) => d >= from && d <= to),
  ]
    .filter((d, i, all) => all.indexOf(d) === i)
    .sort()
    .map((date) => ({
      date,
      kind: MUHURAT[date] === undefined ? 'dr' : 'muhurat',
      windows: MUHURAT[date] === undefined ? DR_WINDOWS : [MUHURAT_WINDOW],
      // A weekend bhavcopy proves the session; on a weekday the archive only shows that some session was held.
      dateConfidence: cal.weekendSessions.includes(date) ? 'archive' : 'recalled',
      timesConfidence: 'recalled',
      source: MUHURAT[date] ?? 'weekend bhavcopy exists (special or disaster-recovery session)',
    }));
  return `// Generated by tools/makeArchiveCalendar.ts from the files NSE published for each date. Do not edit.
// Range ${from} to ${to}; ${cal.sessions.length} sessions, ${holidays.length} holidays, ${special.length} special sessions.
export const ARCHIVE_FROM = '${from}';

export const ARCHIVE_HOLIDAYS: Array<{
  date: string;
  name: string;
  confidence: 'archive';
  source: string;
}> = ${JSON.stringify(holidays, null, 2)} as never;

export const ARCHIVE_SPECIAL: Array<{
  date: string;
  kind: 'budget' | 'dr' | 'muhurat';
  windows: Array<{ open: string; close: string }>;
  dateConfidence: 'archive' | 'recalled';
  timesConfidence: 'recalled' | 'unconfirmed';
  source: string;
}> = ${JSON.stringify(special, null, 2)} as never;
`;
}

async function main(): Promise<number> {
  const from = option('--from');
  const to = option('--to');
  if (from === undefined || to === undefined) {
    console.error('Usage: pnpm tsx tools/makeArchiveCalendar.ts --from YYYY-MM-DD --to YYYY-MM-DD');
    return 2;
  }
  const store = new FileRawStore(option('--dir') ?? 'data/raw/nse-bars');
  const cal = deriveCalendar(await dayEvidence(store), from, to);
  console.log(
    JSON.stringify({
      sessions: cal.sessions.length,
      holidays: cal.holidays.length,
      weekendSessions: cal.weekendSessions,
      uncertain: cal.uncertain.length,
    }),
  );
  if (cal.uncertain.length > 0) {
    console.error(
      `Not written: ${cal.uncertain.length} weekdays are unsettled, for example ${cal.uncertain.slice(0, 8).join(', ')}`,
    );
    return 1;
  }
  writeFileSync(
    join('packages', 'core', 'src', 'calendar', 'archiveCalendar.generated.ts'),
    render(from, to, cal),
    'utf8',
  );
  console.log(`written for ${from} to ${to}`);
  return 0;
}

main().then(
  (code) => process.exit(code),
  (e: unknown) => {
    console.error(e);
    process.exit(2);
  },
);
